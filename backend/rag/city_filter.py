def _find_city_in_query(query: str) -> str | None:
    q = query.lower()

    for canonical, aliases in CITY_ALIASES.items():
        for alias in sorted(aliases, key=len, reverse=True):
            idx = 0
            while True:
                pos = q.find(alias, idx)
                if pos == -1:
                    break
                # Проверка границ
                left_ok = pos == 0 or not q[pos - 1].isalpha()
                right_ok = (pos + len(alias)) >= len(q) or not q[pos + len(alias)].isalpha()
                if left_ok and right_ok:
                    return canonical
                idx = pos + 1
    return None


def filter_by_city(
    query: str,
    chunks: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    city = _find_city_in_query(query)

    if city is None:
        logger.info("City filter: no city in query, passing %d chunks through", len(chunks))
        return chunks

    filtered = []
    for chunk in chunks:
        chunk_city = chunk.get("city") or ""  # None и "" одинаково — «без города»
        if chunk_city == city or not chunk_city:
            filtered.append(chunk)

    logger.info(
        "City filter: query mentions '%s', filtered %d → %d chunks",
        city, len(chunks), len(filtered)
    )

    return filtered


